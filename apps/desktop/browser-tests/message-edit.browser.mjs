import { test, expect } from '@playwright/test';
for (const width of [360, 1000]) test(`user message rejected edit retains draft and retries at ${width}px`, async ({ page }) => {
 await page.setViewportSize({ width, height: 800 });
 await page.goto('/?message-edit');
 const edit = page.getByRole('button', { name: 'Edit message', exact: true });
 await edit.focus(); await page.keyboard.press('Enter');
 const input = page.getByRole('textbox');
 await expect(input).toBeFocused();
 await input.fill('  Revised message 项目  ');
 await input.press('Enter');
 await expect(page.getByLabel('Submitted')).toHaveText('["Revised message 项目"]');
 await expect(input).toBeDisabled();
 await expect(page.getByRole('button', { name: 'Sending...', exact: true })).toBeDisabled();
 await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled();
 await page.getByRole('button', { name: 'Reject request', exact: true }).click();
 await expect(input).toHaveValue('  Revised message 项目  ');
 await expect(input).toBeEnabled();
 const send = page.getByRole('button', { name: 'Send', exact: true });
 await expect(send).toBeEnabled();
 await expect(page.getByText('Failed to edit message', { exact: true })).toBeVisible();
 await send.focus(); await page.keyboard.press('Space');
 await expect(page.getByLabel('Submitted')).toHaveText('["Revised message 项目","Revised message 项目"]');
 await expect(input).toBeDisabled();
 await page.getByRole('button', { name: 'Resolve request', exact: true }).click();
 await expect(input).toHaveCount(0);
 await expect(page.getByText('Revised message 项目', { exact: true })).toBeVisible();
 await edit.focus(); await page.keyboard.press('Enter');
 await expect(input).toHaveValue('Revised message 项目');
 await input.fill('Unsaved replacement');
 await input.press('Escape');
 await expect(input).toHaveCount(0);
 await expect(page.getByText('Revised message 项目', { exact: true })).toBeVisible();
 await expect(page.getByLabel('Submitted')).toHaveText('["Revised message 项目","Revised message 项目"]');
});
